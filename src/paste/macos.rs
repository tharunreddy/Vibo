//! macOS receipt-sequenced reliable paste using `NSPasteboard` lazy promises
//! (`declareTypes:owner:`) and direct `CGEvent` `Cmd+V` injection.

use crate::paste::input::{HeldPasteChord, press_paste_chord, release_paste_chord};
use crate::paste::{CHORD_HOLD_MS, TxState, WaitDecision, evaluate};
use dispatch2::DispatchQueue;
use objc2::rc::Retained;
use objc2::{AnyThread, DefinedClass, define_class, msg_send};
use objc2_app_kit::{
    NSPasteboard, NSPasteboardTypePNG, NSPasteboardTypeString, NSPasteboardTypeTIFF,
};
use objc2_foundation::{NSArray, NSData, NSInteger, NSObject, NSString};
use std::sync::{Arc, Mutex, mpsc};
use std::thread;
use std::time::{Duration, Instant};

/// Concealment markers so third-party clipboard managers (Maccy, Paste, etc.) ignore transient pastes.
const CONCEALMENT_TYPES: [&str; 3] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
];

struct ProviderIvars {
    state: Arc<Mutex<TxState>>,
    text: String,
}

define_class!(
    #[unsafe(super(NSObject))]
    #[name = "ViboPasteProvider"]
    #[ivars = ProviderIvars]
    struct ViboPasteProvider;

    impl ViboPasteProvider {
        #[unsafe(method(pasteboard:provideDataForType:))]
        fn pasteboard_provide_data_for_type(&self, pasteboard: &NSPasteboard, data_type: &NSString) {
            let ivars = self.ivars();
            let is_text = unsafe { data_type.isEqualToString(NSPasteboardTypeString) };
            if is_text
                && let Ok(mut state) = ivars.state.lock()
            {
                state.record_receipt(Instant::now());
            }
            let payload = if is_text {
                NSString::from_str(&ivars.text)
            } else {
                NSString::from_str("")
            };
            let _ = pasteboard.setString_forType(&payload, data_type);
        }

        #[unsafe(method(pasteboardChangedOwner:))]
        fn pasteboard_changed_owner(&self, _pasteboard: &NSPasteboard) {
            if let Ok(mut state) = self.ivars().state.lock() {
                state.ownership_lost = true;
            }
        }
    }
);

impl ViboPasteProvider {
    fn new(state: Arc<Mutex<TxState>>, text: String) -> Retained<Self> {
        let this = Self::alloc().set_ivars(ProviderIvars { state, text });
        unsafe { msg_send![super(this), init] }
    }
}

enum SavedClipboard {
    Empty,
    Text(String),
    Png(Vec<u8>),
    Tiff(Vec<u8>),
}

fn snapshot_clipboard() -> SavedClipboard {
    let pb = NSPasteboard::generalPasteboard();
    if let Some(text) = unsafe { pb.stringForType(NSPasteboardTypeString) } {
        let s = text.to_string();
        if !s.is_empty() {
            return SavedClipboard::Text(s);
        }
    }
    if let Some(png) = unsafe { pb.dataForType(NSPasteboardTypePNG) } {
        let bytes = unsafe { png.as_bytes_unchecked() }.to_vec();
        if !bytes.is_empty() {
            return SavedClipboard::Png(bytes);
        }
    }
    if let Some(tiff) = unsafe { pb.dataForType(NSPasteboardTypeTIFF) } {
        let bytes = unsafe { tiff.as_bytes_unchecked() }.to_vec();
        if !bytes.is_empty() {
            return SavedClipboard::Tiff(bytes);
        }
    }
    SavedClipboard::Empty
}

fn write_plain_text(text: &str) {
    let pb = NSPasteboard::generalPasteboard();
    pb.clearContents();
    let ns_text = NSString::from_str(text);
    let _ = unsafe { pb.setString_forType(&ns_text, NSPasteboardTypeString) };
}

fn restore_clipboard(saved: &SavedClipboard) {
    let pb = NSPasteboard::generalPasteboard();
    pb.clearContents();
    match saved {
        SavedClipboard::Empty => {}
        SavedClipboard::Text(text) => {
            let ns_text = NSString::from_str(text);
            let _ = unsafe { pb.setString_forType(&ns_text, NSPasteboardTypeString) };
        }
        SavedClipboard::Png(bytes) => {
            let data = NSData::with_bytes(bytes);
            let _ = unsafe { pb.setData_forType(Some(&data), NSPasteboardTypePNG) };
        }
        SavedClipboard::Tiff(bytes) => {
            let data = NSData::with_bytes(bytes);
            let _ = unsafe { pb.setData_forType(Some(&data), NSPasteboardTypeTIFF) };
        }
    }
}

struct MacPending {
    state: Arc<Mutex<TxState>>,
    saved: SavedClipboard,
    change_count: NSInteger,
    provider: Option<Retained<ViboPasteProvider>>,
    preserve_clipboard: bool,
    transcript: String,
    held_chord: Option<HeldPasteChord>,
    settled: bool,
}

// SAFETY: `MacPending`'s Objective-C `provider` is only created, read, and dropped on the
// macOS main thread via `DispatchQueue::main()`. Background threads only read `settled` / `state`.
unsafe impl Send for MacPending {}

static PENDING: Mutex<Option<Arc<Mutex<MacPending>>>> = Mutex::new(None);
static PASTE_LOCK: Mutex<()> = Mutex::new(());

fn settle_on_main(pending: &Arc<Mutex<MacPending>>) {
    let mut p = match pending.lock() {
        Ok(p) => p,
        Err(_) => return,
    };
    if p.settled {
        return;
    }
    p.settled = true;

    if let Some(held) = p.held_chord.take() {
        release_paste_chord(held);
    }

    let ownership_lost = p.state.lock().map(|st| st.ownership_lost).unwrap_or(true);
    let still_ours =
        !ownership_lost && NSPasteboard::generalPasteboard().changeCount() == p.change_count;

    if !still_ours {
        tracing::debug!("Clipboard changed externally; leaving untouched");
    } else if !p.preserve_clipboard {
        write_plain_text(&p.transcript);
        tracing::debug!("Left transcript on clipboard as plain text");
    } else {
        restore_clipboard(&p.saved);
        tracing::debug!("Restored previous clipboard");
    }

    p.provider = None;
}

fn flush_pending_on_main() {
    let previous = PENDING.lock().unwrap_or_else(|e| e.into_inner()).take();
    if let Some(prev) = previous {
        settle_on_main(&prev);
    }
}

fn spawn_waiter(pending: Arc<Mutex<MacPending>>) {
    thread::spawn(move || {
        let chord_held = pending.lock().is_ok_and(|p| p.held_chord.is_some());
        if chord_held {
            thread::sleep(Duration::from_millis(CHORD_HOLD_MS));
            let pending_for_release = Arc::clone(&pending);
            DispatchQueue::main().exec_async(move || {
                let held = pending_for_release
                    .lock()
                    .ok()
                    .and_then(|mut p| p.held_chord.take());
                if let Some(held) = held {
                    release_paste_chord(held);
                }
            });
        }

        loop {
            thread::sleep(Duration::from_millis(15));
            let decision = {
                let Ok(p) = pending.lock() else { return };
                if p.settled {
                    return;
                }
                let Ok(st) = p.state.lock() else { return };
                evaluate(&st, Instant::now())
            };
            if let WaitDecision::Finish = decision {
                break;
            }
        }

        let pending_for_finish = Arc::clone(&pending);
        DispatchQueue::main().exec_async(move || {
            settle_on_main(&pending_for_finish);
            if let Ok(mut slot) = PENDING.lock() {
                let is_us = slot
                    .as_ref()
                    .is_some_and(|current| Arc::ptr_eq(current, &pending_for_finish));
                if is_us {
                    *slot = None;
                }
            }
        });
    });
}

fn run_on_main(text: &str, preserve_clipboard: bool) -> Result<(), String> {
    flush_pending_on_main();

    let saved = if preserve_clipboard {
        snapshot_clipboard()
    } else {
        SavedClipboard::Empty
    };

    let state = Arc::new(Mutex::new(TxState::new()));
    let provider = ViboPasteProvider::new(Arc::clone(&state), text.to_string());
    let pasteboard = NSPasteboard::generalPasteboard();

    let mut types: Vec<Retained<NSString>> = Vec::with_capacity(1 + CONCEALMENT_TYPES.len());
    types.push(NSString::from_str("public.utf8-plain-text"));
    for t in CONCEALMENT_TYPES {
        types.push(NSString::from_str(t));
    }
    let types = NSArray::from_retained_slice(&types);

    let change_count: NSInteger =
        unsafe { msg_send![&*pasteboard, declareTypes: &*types, owner: &*provider] };
    if change_count <= 0 {
        return Err("NSPasteboard declareTypes:owner: failed".to_string());
    }

    if let Ok(mut st) = state.lock() {
        st.injected_at = Some(Instant::now());
    }

    let held_chord = match press_paste_chord() {
        Ok(held) => Some(held),
        Err(err) => {
            if let Ok(mut st) = state.lock() {
                st.injection_failed = true;
            }
            tracing::error!(error = %err, "Failed to post Cmd+V CGEvent");
            return Err(err);
        }
    };

    let pending = Arc::new(Mutex::new(MacPending {
        state,
        saved,
        change_count,
        provider: Some(provider),
        preserve_clipboard,
        transcript: text.to_string(),
        held_chord,
        settled: false,
    }));
    *PENDING.lock().unwrap_or_else(|e| e.into_inner()) = Some(Arc::clone(&pending));
    spawn_waiter(pending);
    Ok(())
}

pub fn paste_on_main_sync(text: &str, preserve_clipboard: bool) -> Result<(), String> {
    let _guard = PASTE_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let text = text.to_string();
    let (tx, rx) = mpsc::sync_channel(1);
    DispatchQueue::main().exec_async(move || {
        let res = run_on_main(&text, preserve_clipboard);
        let _ = tx.send(res);
    });
    rx.recv()
        .map_err(|_| "Main thread dropped paste request".to_string())?
}

pub fn copy_plain_text_async(text: &str) {
    let text = text.to_string();
    DispatchQueue::main().exec_async(move || {
        flush_pending_on_main();
        write_plain_text(&text);
    });
}
